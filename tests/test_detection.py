"""Регрессионные тесты идентификации ПД на «сложных предложениях».

Каждый кейс — предложение и ожидаемый список (тип, значение) найденных спанов.
Это оракул качества детекции: покрытие всех типов, вариации форматов, ловушки
(публичные лица, адрес отделения банка, даты договоров, номера заказов) и
запрет избыточного маскирования служебных слов.
"""
from __future__ import annotations

import pytest

from app.engine import analyze, mask_text


def spans_of(text: str) -> list[tuple[str, str]]:
    spans, _ = analyze(text)
    return [(s.type, text[s.start:s.end]) for s in spans]


# --- ФИО ---------------------------------------------------------------------

@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("Вчера звонил Сергей Кузнецов, просил перезвонить", [("fio", "Сергей Кузнецов")]),
        ("Договор подписал Кузнецов С.В. лично", [("fio", "Кузнецов С.В.")]),
        ("Мария Ивановна и Пётр Сидорович пришли вместе", [("fio", "Мария Ивановна"), ("fio", "Пётр Сидорович")]),
        ("ФИО: ИВАНОВ ИВАН ИВАНОВИЧ", [("fio", "ИВАНОВ ИВАН ИВАНОВИЧ")]),
        ("Иванов И.И., Петров П.П.", [("fio", "Иванов И.И."), ("fio", "Петров П.П.")]),
        ("Здравствуйте, меня зовут Ольга", [("fio", "Ольга")]),
        ("Сотрудник Мария Кузнецова, тел. 123-45-67", [("fio", "Мария Кузнецова"), ("phone", "123-45-67")]),
        ("Директор Петров Сергей звонил", [("fio", "Петров Сергей")]),
    ],
)
def test_fio_variants(text: str, expected: list[tuple[str, str]]) -> None:
    assert spans_of(text) == expected


def test_salutation_not_masked() -> None:
    # Обращение — служебное слово, маскируется только имя.
    assert spans_of("Уважаемый Сергей Петрович! Ваш ИНН 500100732259") == [
        ("fio", "Сергей Петрович"), ("inn", "500100732259"),
    ]
    assert mask_text("Уважаемая Анна Сергеевна, ваш заказ готов")[0] == "Уважаемая **** *********, ваш заказ готов"


def test_multiple_people_in_one_text() -> None:
    text = "Иванов Иван Иванович и Петрова Анна Сергеевна, паспорта 4509 123456 и 4510 654321"
    assert spans_of(text) == [
        ("fio", "Иванов Иван Иванович"), ("fio", "Петрова Анна Сергеевна"),
        ("passport", "4509"), ("passport", "123456"), ("passport", "4510"), ("passport", "654321"),
    ]


