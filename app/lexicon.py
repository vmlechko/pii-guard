# Падежные окончания по последней букве имени (для согласной — окончания добавляются).
_ENDINGS: dict[str, tuple[str, ...]] = {
    "й": ("я", "ю", "ем", "е"),
    "ь": ("я", "ю", "ем", "е", "и", "ью"),
    "а": ("ы", "и", "е", "у", "ой", "ою"),
    "я": ("и", "е", "ю", "ей", "ею"),
}
_CONSONANT_ENDINGS = ("а", "у", "ом", "е")
_IRREGULAR: dict[str, set[str]] = {"Лев": {"Льва", "Льву", "Львом", "Льве"}}


def _forms(name: str) -> set[str]:
    """Именительный + косвенные падежи по простым правилам склонения имён."""
    endings = _ENDINGS.get(name[-1])
    stem = name[:-1] if endings else name
    forms = {name} | {stem + e for e in (endings or _CONSONANT_ENDINGS)}
    return forms | _IRREGULAR.get(name, set())


FIRST_NAMES: frozenset[str] = frozenset(
    f.lower() for n in (_MALE + _FEMALE).split() for f in _forms(n)
)
