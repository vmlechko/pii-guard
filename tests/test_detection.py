# --- ловушки: НЕ маскировать ---------------------------------------------------

@pytest.mark.parametrize(
    "text",
    [
        "поэт Александр Пушкин написал роман",
        "Толстой Лев Николаевич написал Войну и мир",
        "Отделение банка: г. Москва, ул. Ленина, д. 1",
        "Отделение банка находится по адресу: г. Москва, ул. Ленина, д. 1, офис 5",
        "В Москве открылся новый офис",
        "Заказ №4509 от 123456 руб.",
        "код 123-456 не подходит, версия 1.2.3, сумма 1000000000 руб",
        "Встреча 12.04.2024 в 10:00",
        "Договор от 12.04.2024, оплата до 30.06.2024",
        "ivan@localhost",
    ],
)
def test_traps_not_masked(text: str) -> None:
    assert spans_of(text) == []
    assert mask_text(text)[0] == text


def test_client_address_kept_but_bank_office_skipped() -> None:
    text = (
        "Клиент банка Иванов проживает: г. Москва, ул. Ленина, д. 5. "
        "Ближайшее отделение банка: г. Москва, ул. Мира, д. 2"
    )
    out, _ = mask_text(text)
    assert out.startswith("Клиент банка Иванов проживает: г. ******, ул. ******, д. *.")
    assert out.endswith("Ближайшее отделение банка: г. Москва, ул. Мира, д. 2")


def test_bare_dept_code_needs_passport_context() -> None:
    assert spans_of("Заявка 123-456") == []
    assert ("dept_code", "770-001") in spans_of("паспорт 4509 123456, 770-001")
